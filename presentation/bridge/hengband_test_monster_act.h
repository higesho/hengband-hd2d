/*!
 * @file hengband_test_monster_act.h
 * @brief 検査用の「敵の行動を指定する入口」（変愚蛮怒・短愚蛮怒のコアだけが組む）
 * @details
 * 環境変数 `HD2D_TEST_MONSTER_ACT` に命令ファイルのパスが入っているときだけ効く。無ければ何もしない
 * （ふだんの遊び・配布物には効かない）。コアがプレイヤーの次のキーを待っている間に、そのファイルがあれば
 * 読み、命令を上から順に実行し、ファイルを消す（消せなければ名前を変える）。
 *
 * ## 複数行
 * 1 つのファイルに複数行を書ける。上から順に、**1 回の命令待ちの中で全部**実行する（その間ゲームの時間は進まない）。
 * 空行と `#` で始まる行は読み飛ばす。実行した行ごとに 1 行ずつ標準エラーへ出す。
 *
 *     [test-monster-act] ok <行>
 *     [test-monster-act] fail <理由>: <行>
 *     [test-monster-act] skip <行>
 *
 * 途中で `fail` したら、残りの行は実行せず、行ごとに `skip` を出す。
 *
 * ## 命令（1 行 1 命令。空白区切り。`<対象>` は `nearest`・m_idx の数字）
 *
 * - `cast <魔法の名前> [<対象>]` … 指定の敵に、その魔法をプレイヤーへ向けて、いま撃たせる。
 *   魔法の名前は原作の旗の名前（`BR_FIRE`・`BO_COLD`・`BA_POIS`・`MISSILE`・`BLINK` など。
 *   `MonsterAbilityType::` を外した名前。原作の `r_info_ability_flags` の表で引く）。
 *   省略時は見えているいちばん近い敵。
 * - `melee [<対象>]` … 指定の敵に、いまプレイヤーへ直接攻撃させる。隣にいるときだけ。
 * - `place <対象> <dx> <dy>` … その敵を、プレイヤーの位置から (dx, dy) ずれたマス（dy は下が正）へ動かす。時間は使わない。
 *   地図の外・立てない地形（壁・ドアなど）・ほかの敵やプレイヤーがいるマスは `fail`（敵は動かない）。立てるかの判定は、
 *   原作が敵をテレポートさせる `cave_monster_teleportable_bold()`。動かしたあとの更新は、原作の `teleport_monster_to()` と同じ
 *   （マスの付け替え・`update_monster()`・`lite_spot()`）。
 * - `hold <対象|all> on|off` … on の間、その敵は自分の番に行動しない（動かない・魔法を撃たない・殴らない）。
 *   入口から命じた `cast` / `melee` / `place` は働く。`all` は、いまいる敵と、あとから現れる敵のすべて。
 *   実装は、命令待ちのたびに、止めている敵の `energy_need`（次の行動までに必要なエネルギー。原作の
 *   `sweep_monster_process()` が毎ターン速度ぶん引いて、0 以下で行動させる）を大きな値に置き直す。
 *   止める前の値を覚えておき、off で戻す。敵の状態（睡眠・恐怖など）は変えない。副作用は、止めている間
 *   `energy_need` が書き換わっていること（この間にセーブすると値が残る）。止めている敵が死んだ・階が替わって
 *   同じ番号に別の敵が入った・置いた値が書き換えられたときは、記録から外す（値は戻さない）。
 *
 * 命令ファイルは、一時ファイルへ書いてから名前を付け替えて置くこと（書きかけを読まないため）。
 *
 * ## 実行する条件
 * コマンド待ち（`inkey_flag`）のときだけ実行する。メニュー・店・問い・`-more-` の待ちの間は、
 * ファイルを置いたまま待つ（次にコマンド待ちになったとき実行する）。
 *
 * 呼び出し箇所は `presentation/term/sdl_null_term.cpp` の入力待ちの周回。**短愚蛮怒と変愚蛮怒だけが
 * このファイルを組む**（Windows は両方の vcxproj、Android・Linux は変愚・短愚のコアの glob だけ）。
 */
