//! kind 別 id→tile_index 索引を初回参照時に構築する（全量索引の線形探索回避・O(1)）。
inline const std::unordered_map<uint16_t, uint16_t> &index_for_kind(char kind)
{
    static const std::unordered_map<uint16_t, uint16_t> r_index = [] {
        std::unordered_map<uint16_t, uint16_t> m;
        for (const auto &e : kOfficialTiles) {
            if (e.kind == 'R') {
                m.emplace(e.id, e.tile_index);
            }
        }
        // shared_ids 別名を後入れする。emplace は既存キーを上書きしないため
        // 実体を持つ直接エントリが常に優先される（B-07）。
        for (const auto &a : kOfficialTileAliases) {
            if (a.kind == 'R') {
                m.emplace(a.id, a.tile_index);
            }
        }
        return m;
    }();
    static const std::unordered_map<uint16_t, uint16_t> k_index = [] {
        std::unordered_map<uint16_t, uint16_t> m;
        for (const auto &e : kOfficialTiles) {
            if (e.kind == 'K') {
                m.emplace(e.id, e.tile_index);
            }
        }
        // shared_ids 別名を後入れする。emplace は既存キーを上書きしないため
        // 実体を持つ直接エントリが常に優先される（B-07）。
        for (const auto &a : kOfficialTileAliases) {
            if (a.kind == 'K') {
                m.emplace(a.id, a.tile_index);
            }
        }
        return m;
    }();
    static const std::unordered_map<uint16_t, uint16_t> f_index = [] {
        std::unordered_map<uint16_t, uint16_t> m;
        for (const auto &e : kOfficialTiles) {
            if (e.kind == 'F') {
                m.emplace(e.id, e.tile_index);
            }
        }
        // shared_ids 別名を後入れする。emplace は既存キーを上書きしないため
        // 実体を持つ直接エントリが常に優先される（B-07）。
        for (const auto &a : kOfficialTileAliases) {
            if (a.kind == 'F') {
                m.emplace(a.id, a.tile_index);
            }
        }
        return m;
    }();
    static const std::unordered_map<uint16_t, uint16_t> p_index = [] {
        std::unordered_map<uint16_t, uint16_t> m;
        for (const auto &e : kOfficialTiles) {
            if (e.kind == 'P') {
                m.emplace(e.id, e.tile_index);
            }
        }
        // shared_ids 別名を後入れする。emplace は既存キーを上書きしないため
        // 実体を持つ直接エントリが常に優先される（B-07）。
        for (const auto &a : kOfficialTileAliases) {
            if (a.kind == 'P') {
                m.emplace(a.id, a.tile_index);
            }
        }
        return m;
    }();
    static const std::unordered_map<uint16_t, uint16_t> empty_index;
    switch (kind) {
    case 'R':
        return r_index;
    case 'K':
        return k_index;
    case 'F':
        return f_index;
    case 'P':
        return p_index;
    default:
        return empty_index;
    }
}

