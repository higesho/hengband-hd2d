/*!
 * @file sound_event.h
 * @brief 音の出来事を画面へ運ぶ形
 *
 * ## なぜコアが鳴らさないのか
 * 位置で聞き分けるには「音源のマス」「**聞き手の位置と向き**」「HRTF の効くミキサ」が要る。
 * コアには後ろ 2 つが無い（カメラを知らない）。だから**コアは出来事だけを言い**、
 * 鳴らすのは画面側（`hd2d/audio/`）にする——2026-08-21 に決めた。
 *
 * 形は `CombatFxEvent`（`combat_fx.h`）と同じ考え方である。あちらが「どのマスで何が起きたか」を
 * 既に運んでいるので、**同じ配管に 1 つ足すだけ**で済む。
 *
 * ## 距離は 2 つある（§4.1）
 * **直線距離で減衰させてはいけない。** Sil-Q の騒音は壁を通らず扉で +5 される
 * 幅優先探索（`update_flow`）で、`path` はその**曲がり角を回った道のり**である。
 * 壁 1 枚隔てた隣の敵は「近い」のではなく「通路をぐるりと回った分だけ遠い」。
 *
 * | 量 | 何に使うか |
 * |---|---|
 * | `path` | **音量**（減衰） |
 * | `heard_y` / `heard_x` | **方向**（定位）。回折して聞こえる曲がり角のマス |
 *
 * どちらも**コアが計算して載せる**。画面側は既知のマスしか持たないので、あちらで
 * 探索すると**居ない角から音が鳴る**（§4.1「誰が計算するか」）。
 *
 * @note 載っていなければ（`path == 0` / `heard_*` が 0,0）画面側は
 * **実際のマスと直線距離へ落ちる**。コア名で分岐しないための約束で、
 * `has_sub_panel_kinds` と同じ流儀（v1 §3.2 の「未知は捨てる・既定へ落ちる」）。
 */
#pragma once

#include <cstdint>
#include <string>

//! 音 1 つ。**名前で運ぶ**（番号は変種ごとに違う。名前なら `hit` は `hit` である）。
struct SoundEvent {
    /*!
     * @brief 音の名前（`angband_sound_name` の綴り。`hit` `kill` `opendoor` …）。
     * @details **番号を運ばない。**同じ番号が変種ごとに別の音を指すので、番号で運ぶと
     * 画面側に変種ごとの対応表が要る（＝コア名の分岐が生える）。名前なら表は 1 つで済む。
     */
    std::string name;
    //! 実際に鳴ったマス。**位置が分からない音は聞き手と同じマス**を入れる（頭で鳴る）。
    int16_t y{ 0 };
    int16_t x{ 0 };
    /*!
     * @brief 聞こえてくるマス（**回折の曲がり角**）。0,0 なら「計算していない」。
     * @details 求め方は「聞き手から音の道を辿り、**視線が通らなくなる 1 つ手前**」。
     * 音源が見えているときは実際のマスと同じになる。
     */
    int16_t heard_y{ 0 };
    int16_t heard_x{ 0 };
    //! 音の道のり（歩数。閉じた扉の +5 などを含む）。**0 なら「計算していない」**。
    uint16_t path{ 0 };
    //! 音そのものの大きさ（0..255 ＝ 0..1 倍）。**距離の減衰はこれとは別**に掛かる。
    uint8_t gain{ 255 };
};
