//! 「、」で区切って並べる。
std::string join_comma(const std::vector<std::string> &items) {
    std::string out;
    for (std::size_t i = 0; i < items.size(); ++i) {
        if (i != 0) {
            out += "\343\200\201" /*、*/;
        }
        out += items[i];
    }
    return out;
}

//! 全部を知っているときの値（回数・攻撃の知識の上限）。
constexpr uint8_t kKnowsAll = UCHAR_MAX;

//! ウィザードモードの知識の初期化に当たる処理を、写しの知識に対して行う（原作の memory は書き換えない）。
void wizard_mode_init(Recall_t &memory, Creature_t const &creature) {
    const uint32_t flags = creature.movement;
    memory.kills = static_cast<uint16_t>(SHRT_MAX);
    memory.wake = kKnowsAll;
    memory.ignore = kKnowsAll;

    // 持ち物の確率を表す値（movement の上位ビットへ入れる）。
    const uint32_t carry_chance = ((flags & mv::CM_4D2_OBJ) != 0u ? 8u : 0u) + ((flags & mv::CM_2D2_OBJ) != 0u ? 4u : 0u)
                                  + ((flags & mv::CM_1D2_OBJ) != 0u ? 2u : 0u) + ((flags & mv::CM_90_RANDOM) != 0u ? 1u : 0u)
                                  + ((flags & mv::CM_60_RANDOM) != 0u ? 1u : 0u);

    memory.movement = (flags & ~mv::CM_TREASURE) | (carry_chance << mv::CM_TR_SHIFT);
    memory.defenses = (uint16_t) creature.defenses;

    // 呪文の頻度のビットが立っているときだけ、頻度のビットを全部立てる。
    const bool has_freq = (creature.spells & sp::CS_FREQ) != 0u;
    memory.spells = has_freq ? (creature.spells | sp::CS_FREQ) : creature.spells;

    // 攻撃の欄は、定義のある分だけ全部知っていることにする。
    for (int slot = 0; slot < MON_MAX_ATTACKS && creature.damage[slot] != 0; ++slot) {
        memory.attacks[slot] = kKnowsAll;
    }

    // Quylthulg など、魔法だけで攻撃する怪物の情報を出すための細工。
    if ((memory.movement & mv::CM_ONLY_MAGIC) != 0u) {
        memory.attacks[0] = kKnowsAll;
    }
}

