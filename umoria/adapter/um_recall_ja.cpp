std::string recall_japanese(int monster_id) {
    if (monster_id < 0 || monster_id >= MON_MAX_CREATURES) {
        return std::string();
    }

    // 知識の写し。ウィザードモードのときだけ原作と同じに全部を知っていることにする（本物は書き換えない）。
    Recall_t memory = creature_recall[monster_id];
    const Creature_t &creature = creatures_list[monster_id];

    if (game.wizard_mode) {
        wizard_mode_init(memory, creature);
    }

    auto spells = (uint32_t) (memory.spells & creature.spells & ~sp::CS_FREQ);

    // CM_WIN の性質はいつでも分かっている。
    auto move = (uint32_t) (memory.movement | (creature.movement & mv::CM_WIN));

    const uint16_t known_defense = memory.defenses & creature.defenses;

    std::string out = tr(creature.name) + ":\n";

    // 最初の段落（核となる説明）。
    out += conflict_history(memory.deaths, memory.kills);
    std::vector<Clause> clauses;
    depth_found_at(creature.level, memory.kills, clauses);
    movement(move, creature.speed, clauses);
    if (!clauses.empty()) {
        out += clauses_to_sentence(clauses);
    }

    if (memory.kills != 0u) {
        out += kill_points(creature.defenses, creature.kill_exp_value, creature.level);
    }

    out += magic_skills(spells, memory.spells, creature.spells);
    out += kill_difficulty(creature, memory.kills);
    out += special_abilities(move);
    out += weaknesses(known_defense);

    if ((known_defense & df::CD_INFRA) != 0 && (known_defense & df::CD_NO_SLEEP) != 0) {
        out += "\343\201\235\343\202\214\343\201\257\346\270\251\350\241\200\345\213\225\347\211\251\343\201\247\343\201\202\343\202\212\343\200\201\351\255\205\344\272\206\343\202\202\347\235\241\347\234\240\343\202\202\345\212\271\343\201\213\343\201\252\343\201\204\343\200\202" /*それは温血動物であり、魅了も睡眠も効かない。*/;
    } else if ((known_defense & df::CD_INFRA) != 0) {
        out += "\343\201\235\343\202\214\343\201\257\346\270\251\350\241\200\345\213\225\347\211\251\343\201\247\343\201\202\343\202\213\343\200\202" /*それは温血動物である。*/;
    } else if ((known_defense & df::CD_NO_SLEEP) != 0) {
        out += "\343\201\235\343\202\214\343\201\257\351\255\205\344\272\206\343\202\202\347\235\241\347\234\240\343\202\202\345\212\271\343\201\213\343\201\252\343\201\204\343\200\202" /*それは魅了も睡眠も効かない。*/;
    }

    out += awareness(creature, memory);
    out += loot_carried(creature.movement, move);
    out += attack_number_and_damage(memory, creature);

    // 勝利の怪物は常に分かっている。
    if ((creature.movement & mv::CM_WIN) != 0u) {
        out += "\343\201\223\343\202\214\343\202\222\345\200\222\343\201\233\343\201\260\343\202\262\343\203\274\343\203\240\343\201\253\345\213\235\345\210\251\343\201\231\343\202\213\357\274\201" /*これを倒せばゲームに勝利する！*/;
    }

    return out;
}

