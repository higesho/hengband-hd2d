//! 節の並びを 1 つの文にする（先頭に「それは」を付け、続ける形をつないで「。」で終える）。
std::string clauses_to_sentence(const std::vector<Clause> &clauses) {
    std::string out = "\343\201\235\343\202\214\343\201\257" /*それは*/;
    for (std::size_t i = 0; i < clauses.size(); ++i) {
        const bool last = i + 1 == clauses.size();
        if (last) {
            out += clauses[i].term;
        } else if (clauses[i + 1].adversative) {
            out += clauses[i].adv + "\343\200\201" /*、*/;
        } else {
            out += clauses[i].ren + "\343\200\201" /*、*/;
        }
    }
    out += "\343\200\202" /*。*/;
    return out;
}

