#pragma once
/*!
 * @file dungeon_style.h
 * @brief ダンジョンごとの意匠（P10 第 4 期。2026-08-10 に決めた）。
 *
 * > 各ダンジョンの地面や壁での差は現状でもある程度あるようだ。
 * > **同質なダンジョンは名前の意味で小物に差を付けよう。**
 * > イークの洞窟はベッドの藁束や食料としている小動物の骨、生えているキノコ。
 * > オークの洞窟はイークの洞窟より大きなベッド、壊れた道具、ゴミの山等
 *
 * **町（`TownStyle`）とまったく同じ流儀である。**骨組み（＝どこに置くか）は 1 つで、
 * **引く名前だけを差し替える**。ライブラリに無ければ基の名前へ落ちるので、表に載せていない
 * ダンジョンは今までの絵のまま動く。
 *
 * 置き場所は `terrain_view.cpp` の装飾層が持っている 4 つ（`floor_meaning.h` の
 * `MARK_*` で決まる）。**確率はここでは変えない**——種類を替えるだけにしてある。
 *
 * | 枠 | 条件 | 既定 |
 * |---|---|---|
 * | ① 行き止まり | `MARK_DEAD_END` | 瓦礫（必ず）＋ 45% で茸 |
 * | ② 通路の壁際 | `MARK_WALL_SIDE` かつ通路の床。30% | 瓦礫 40 / 骨 30 / 石筍 30 |
 * | ③ 部屋の縁 | `MARK_ROOM_EDGE` | 柱 10% / 立ち松明 6.5%（明るい部屋だけ） |
 * | ④ 部屋の中 | `RoomFloor`。4.5% | 樽 40 / 木箱 35 / 骨 25 |
 *
 * 壁（部屋の構造壁）も差し替えられる。切石積み（`wall_stone`）は「人が積んだ壁」なので、
 * 手掘りの穴と獣の巣には合わない（2026-08-10 に決めた「イークもオークも壁は岩肌で」）。
 */

#include <string>

namespace hd2d {

/*!
 * @brief 1 本のダンジョンの意匠。
 *
 * @details 文字列の約束は 3 通りある。**この 3 つを取り違えると意図が逆になる**ので、
 * 表を書くときは必ず意識すること。
 *
 * - `nullptr` … **既定のまま**（そのダンジョンでは何も差し替えない）
 * - `""` … **置かない**（既定の小物を消す）
 * - 名前 … その名前を引く。**ライブラリに無ければ既定へ落ちる**
 */
struct DungeonStyle {
    /*!
     * @name 役割の既定の材（`nullptr` なら既定のまま）
     *
     * @details 変種は `_01`〜`_10` で集める。**1 枚も無ければ既定へ落ちる。**
     *
     * 効くのは**役割の既定で描くマスだけ**である。地形の細別（水・溶岩・草・木・
     * ガラス・山脈壁…）を持つマスは表のほうが正なので触らない（設計書 §9.4
     * 「ui は地形テーブルを知らない」）。だから「洞窟の床」を指定しても、
     * その洞窟にある池や溶岩は池と溶岩のまま出る。
     * @{
     */
    const char *room_floor_stem; //!< 部屋の床（既定 `floor_room` ＝ 大判の敷石）
    const char *corridor_floor_stem; //!< 通路の床（既定 `floor_rough`）
    const char *wall_stem; //!< 部屋・通路に面した壁（既定 `wall_stone` ＝ 切石積み）
    const char *bedrock_stem; //!< 岩盤＝厚い壁の塊（既定 `bedrock`）
    /*! @} */
    //! ① 行き止まりに必ず置く塚（既定 `rubble_pile`）。
    const char *dead_end_pile;
    //! ② 通路の壁際の 3 つ（既定 `rubble_pile` 40 / `bones` 30 / `stalagmite` 30）。
    const char *wall_side[3];
    //! ③ 部屋の縁の柱（既定 `pillar_stone`）。切石の柱が立たない洞窟では岩へ差し替える。
    const char *room_edge_pillar;
    /*!
     * @brief ③ 部屋の縁の火の本体（既定 `torch_stand`）。
     * @details 立ち松明は**柱と炎の 2 体**でできている（自発光はインスタンス単位なので、
     * 1 体にすると鉄柱まで光る＝既存の作り）。差し替えるときも同じ 2 枠を使う。
     */
    const char *fire_body;
    //! ③ の炎（既定 `torch_flame`）。`""` なら炎を置かない＝**消えている火**になる。
    const char *fire_flame;
    /*!
     * @brief 火を「明るい部屋」に限るか（既定は真）。
     * @details 立ち松明が燃えているのに部屋が暗い、という矛盾を避けるための既定
     * （2026-08-09 に決めた）。**消えている火（焚き火跡）にはこの縛りが要らない**
     * ので、そういう意匠では偽にする。
     */
    bool fire_needs_lit;
    //! ④ 部屋の中の 3 つ（既定 `barrel` 40 / `crate` 35 / `bones` 25）。
    const char *room_floor[3];
    /*!
     * @brief **小物を撒いてよい地形の key** の並び（決めたこと D7。2026-08-21）。
     * `nullptr` が並びの終わり。**書かなければ従来どおり**（1 つも変わらない）。
     *
     * ## なぜ要るのか
     * 上の 4 枠（行き止まり・通路の壁際・部屋の縁・部屋の中）は、`terrain_view.cpp` の
     * 装飾層が**役割の既定で描いたマスにだけ**回している——地形の細別を持つマスに撒くと
     * 「溶岩の上に木箱が浮く」からである（実際に出た）。
     *
     * ところが**草地と木と水しか無いダンジョン**では、それだと**枠が 1 度も回らない**。
     * 幻想蛮怒の無縁塚（7）は細別が **99.4%**、魔法の森深部（3）は **100%** で
     * （全フロア 14,000 マスの実測。2026-08-21）、紫の桜も大キノコも 1 つも置かれていなかった。
     *
     * ## 形
     * **撒いてよい地形を表が名指す。**草地と花だけを挙げれば、木にも水にも溶岩にも
     * 撒かないので過去の失敗は踏まない。**確率も置き方も変えない**——緩めるのは
     * 「どのマスで枠が回るか」だけである（必守制約 4 の但し書き）。
     *
     * 地形は **key の文字列**で書く（id は版で動く。町の `TerrainProp` と同じ流儀で
     * `PrefabLibrary::terrain_id_for_key` が翻訳する）。
     */
    const char *prop_terrains[6];
};

/*!
 * @brief `dungeon_id` と階から意匠を引く。
 * @param dungeon_id `FloorIdentity::dungeon_id`
 * @param dun_level `FloorIdentity::dun_level`。**階の帯**（`levels`）を引くのに使う
 * @return 知らないダンジョンは**全部が既定**の意匠（＝今までの絵）。
 * @note 地上（町・荒野）では呼ばない。呼んでも既定が返るだけだが、
 * 町の地面の分岐と混ざると読みにくくなる。
 *
 * @details 引く順は のとおり:
 * 1. `load_dungeon_styles()` がそのコア名の節を採っていれば**データだけ**を見る
 *    （下のべた書きの表 `kRows` へは落ちない）
 * 2. `id` と `levels` の両方が合う節 ＞ `id` だけ合う節 ＞ `id: 0`（そのコアの既定）
 * 3. データが無ければ従来どおり `kRows`（変愚の 20 本）
 */
const DungeonStyle &dungeon_style_for(int dungeon_id, int dun_level = 0);

/*!
 * @brief **ダンジョンの意匠をデータから読む**。
 *
 * ## なぜ要るのか
 * 上の `dungeon_style_for` は `dungeon_id` だけで引くので、**別のコアでは別のダンジョン**を
 * 指す——変愚の 5 番は竜の住みかだが幻想蛮怒の 5 番は紅魔館深部で、竜の巣の卵殻と鱗が
 * 図書館に散らばっていた。16 本すべてが同じ誤りを持っている。
 *
 * ## 形
 * `<voxel_dir>/dungeon_styles.jsonc` を読み、**握手で受け取ったコア名の節だけ**を採る。
 * `load_town_styles()`（`town_plan.h`）とまったく同じ流儀である:
 *
 * - **コアには 1 行も触らない。** `core_name` は握手（v1 §3.1）で既に届いている
 * - **UI はコアの名前を知らない。** 名前で引くだけで、どの番号が何のダンジョンかはデータが持つ
 * - **表が無い／そのコア名の節が無いなら完全に従来どおり**（変愚の絵は 1 ボクセルも動かない）
 *
 * @param voxel_dir プレハブの置き場（`options.voxel_dir`）
 * @param core_name `hello_ack.core_name`。空なら何もしない
 * @param log 読んだ結果の 1 行（stderr へ出す用。省略可）
 * @return データを 1 本でも採ったか
 * @note **握手の直後に 1 度だけ呼ぶ。**読み直すと、前に返した `DungeonStyle` の中の
 *   `const char *` が宙に浮く（文字列はこの表が持っている。町と同じ注意）。
 */
bool load_dungeon_styles(const std::string &voxel_dir, const std::string &core_name, std::string *log = nullptr);

} // namespace hd2d
