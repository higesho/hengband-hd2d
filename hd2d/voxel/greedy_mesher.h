/*!
 * @file greedy_mesher.h
 * @brief グリーディメッシング（ボクセル → メッシュ）。**色は見ない。**
 *
 * 段取りは P1 ③④。
 *
 * ## 要点（§6.2(a)）
 * **色を頂点に持たせない。**隣と色が違うだけで面をまとめられなくなり、建物で 8 倍損する
 * （店 4,286 → 543 四角形）。ここでは
 *
 * - まとめる条件は「露出しているか」だけ（**形だけ見る**）
 * - パレット索引と AO は**露出面ぶんの 2D アトラス**（`GL_RG8UI`）へ入れる
 * - フラグメントシェーダが `texelFetch` で 1 面 1 テクセルを引く
 *
 * アトラスのテクセル数は「素の面の数」に等しい（店で 110,278 = 512×512 に収まる）。
 * **三角形は 200 分の 1 になり、色の情報量は元のまま**というのがこの作りの取引である。
 *
 * ## 検算
 * `tools/voxel_probe/greedy.py` の第 3 列と**四角形の数が一致すること**。
 * 一致しなければメッシャが間違っている（計画 P1 の検証）。
 * まとめる向き（どちらの軸を先に伸ばすか）で数が変わるので、**軸の順序も
 * greedy.py に合わせてある**（`mesh_model` の実装の注記を読むこと）。
 *
 * ## AO（§13「ボクセルらしさの半分はこれ」）
 * 面ごとに 1 つ焼く。面の外側の隣（空のはず）の周り 8 マスがどれだけ詰まっているかで決める。
 * **頂点ごとではなく面ごと**なのは、まとめた四角形が何十ボクセルにも及ぶため
 * （頂点に持たせると、まとめる条件に AO が加わって四角形の数が跳ね上がる＝検算が壊れる）。
 */
#pragma once

#include "voxel/vox_file.h"

#include <cstdint>
#include <string>
#include <vector>

namespace hd2d {

//! 頂点 1 つ。位置はパーツのローカル（ボクセル単位）、`u`/`v` は**アトラスのテクセル座標**。
struct VoxelVertex {
    float px{};
    float py{};
    float pz{};
    float nx{};
    float ny{};
    float nz{};
    float u{};
    float v{};
    /*!
     * @brief 風の**しなやかさ**（0 = 動かない根元 / 1 = 最もよく動く先端）。P6 ②。
     *
     * @details 設計書 §7.1-3「**自動**（そのパーツの底面からの高さ）＋パーツごとの係数」。
     * ここが自動側で、係数は `PrefabPart::wind_k` が掛かる。
     *
     * **メッシュ化のときに焼く**のがこの作りの要点である（§8.1）。頂点シェーダは
     * これを読むだけなので、木 8,409 本を 1 回の描画で、それぞれ違う位相で揺らせる。
     * @note まとめる条件（露出しているか）には**入れない**。入れると四角形の数が跳ね上がり、
     * `greedy.py` との検算が壊れる（AO を面ごとにした理由と同じ）。高さは頂点位置から
     * 決まるので、まとめた四角形の中でも角ごとに正しい値になる。
     */
    float flex{};
    /*!
     * @name 四角形の縁までの距離（**テクセル**。TRON 画調の「物の稜線」の素）
     *
     * @details。並びは
     * `e0` = 左の縁まで・`e1` = 右の縁まで・`e2` = 下の縁まで・`e3` = 上の縁まで
     * （左右＝アトラスの u 方向＝まとめた軸 `q`、上下＝ `v` 方向＝ `p`）。
     *
     * **4 本とも四角形の中で 1 次式**なので、頂点に置けば補間がそのまま正しい距離になる。
     * 「縁までの最短距離」1 本にすると 4 隅すべてで 0 になり、線形補間では内側の山を
     * 表せない（＝角だけ光って辺が光らない）。4 本要るのはそのためである。
     *
     * ## なぜ「四角形の縁」が稜線なのか
     * グリーディメッシングは**露出している面だけ**をまとめるので、四角形が終わる所は
     * 「そこで面が露出しなくなる」＝**形の折れ目か外周**である。つまり四角形の縁を
     * なぞれば、立体の輪郭と凹凸の稜線がそのまま出る。
     *
     * @note 平らな面が L 字などで 2 つ以上の四角形に割れると、**平面の途中にも縁が出る**
     * （まとめ方の都合であって形の折れ目ではない）。TRON では継ぎ目の線に見えるので
     * 許容する。
     * @note 画調が標準のときは**シェーダが 1 度も読まない**。焼くコストは頂点あたり
     * 16 バイトで、プレハブは共有メッシュなので実体の数には比例しない。
     * @{
     */
    float e0{};
    float e1{};
    float e2{};
    float e3{};
    /*! @} */
};

struct VoxelMesh {
    std::vector<VoxelVertex> vertices;
    std::vector<std::uint32_t> indices;
    std::size_t quad_count{ 0 }; //!< まとめた後の四角形の数（**検算の相手**）
    std::size_t naive_face_count{ 0 }; //!< まとめる前の露出面の数（＝アトラスのテクセル数）
    int atlas_w{ 0 };
    int atlas_h{ 0 };
    //! `RG8UI`。R = パレット索引（1..255）、G = AO（0..255。大きいほど明るい）。
    std::vector<std::uint8_t> atlas;

    std::size_t triangle_count() const { return this->quad_count * 2; }
};

/*!
 * @brief 1 つの模型をメッシュにする。
 * @param[out] err 失敗の理由（アトラスに入り切らなかった等）。
 * @param hide_unseen_from_above **空から見えない面を作らない**（既定は偽＝従来どおり）。
 * @return 成功したか。中身が空の模型は「四角形 0 個の成功」として返る。
 *
 * ## `hide_unseen_from_above` は何のためか（2026-08-25。決めたこと）
 *
 * 深淵（`ground_chasm_sq_*`）は**床の 3 マス下まで漏斗で窄まる殻**である。地形は
 * 空に浮いた板なので、**床より下は隣が空**——殻の**外側**にも面が立ち、下から見ると
 * 漏斗が垂れ下がって見える。決めたことは「**穴が地面側からだけ描画される**ように」。
 *
 * **隣のマスを見て消すことはできない**（プレハブは 1 つずつメッシュ化して並べる）ので、
 * **プレハブの中だけで決められる規則**にした:
 *
 * 1. **模型のいちばん上の面**にある空のボクセルから、空だけを伝って塗り広げる
 *    ＝「**空から届く空間**」
 * 2. 面の向こうが**そこに入っていなければ、その面を作らない**
 * 3. 箱の外へ向く面は、**上（+z）だけ残す**（地面の表。横と下は隣か地面の下）
 *
 * 深淵では、漏斗の内側は口から続いているので**残り**、殻の外側は唇
 * （マスいっぱいに詰まった岩）で空から切れているので**落ちる**。
 * **旗を立てないプレハブは 1 バイトも変わらない。**
 */
bool mesh_model(const VoxModel &model, VoxelMesh &out, std::string &err, bool hide_unseen_from_above = false);

/*!
 * @brief LOD 段を作る（設計書 §6「32 → 16 → 8 → 板 1 枚」／§7.1-5「一旦自動生成」）。
 * @param level 0 = そのまま、1 = 1/2、2 = 1/4 …
 * @details `2^level` 立方のブロックごとに**中身のあるボクセルの多数決**で 1 つへ落とす。
 * 色は「そのブロックで最も多い索引」を採る（平均すると隣の材質と混ざって濁る）。
 *
 * @note **半分以上詰まっていなければ空にする。**「1 つでも詰まっていれば詰まっている」に
 * すると、木の葉のような疎な形が遠景で膨らんで別物になる。
 */
bool downsample_model(const VoxModel &model, int level, VoxModel &out, std::string &err);

} // namespace hd2d
