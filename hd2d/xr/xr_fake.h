/*!
 * @file xr_fake.h
 * @brief 疑似 HMD（`--vr-fake`）。**OpenXR を 1 行も使わない。**
 *
 *
 * ## なぜ要るか
 * 1. **既存の検証の流儀を保つ。** `--vr-fake --shot=out.bmp` で、両眼ぶんの絵が
 *    今までどおり静止画で撮れる（`--shot` は swap 直前のバックバッファを読むので無改修）
 * 2. **ランタイムの都合と描画の不具合を切り分ける。** HMD もランタイムも要らないので、
 *    「絵がおかしい」のか「セッションが立っていない」のかがすぐ分かる
 *
 * ## 実機との違い（承知のうえで割り切っているところ）
 * - 姿勢は**固定**。頭は動かない（頭の追従は実機でしか確かめられない）
 * - コンポジタが無いので、UI のクワッドレイヤは**シーンの中の板**として描くことになる
 *   （M2）。文字のくっきり度だけは実機と差が出る
 */
#pragma once

#include "xr/xr_session.h"

namespace hd2d::xr {

/*!
 * @brief 疑似の 1 フレーム（左右の目の姿勢と画角）を作る。
 * @param eye_w,eye_h 目 1 つぶんの描き先の大きさ（画素）。
 * @param ipd_m 瞳孔間距離（メートル）。既定 64mm は成人の平均。
 * @return `Session::begin_frame` が返すのと同じ形。
 *
 * @details 頭は原点で -z を向いて立っている。**画角はわざと非対称にしてある**——
 * 実機の HMD は左右・上下が独立した角を返すので、対称な値で試すと
 * 「非対称視錐台の実装が間違っていても気づけない」検査になる。
 */
Frame make_fake_frame(int eye_w, int eye_h, float ipd_m = 0.064f);

} // namespace hd2d::xr
