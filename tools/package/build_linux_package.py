# license_docs.copy_dcss (shared with the Windows package). The font license (OFL) is assets/fonts/dcss/OFL.txt.
LIB_ROOTS=['lib','tangband/lib','gensoband/lib','toband/lib','silq/lib','frox/lib']
MUTABLE=['save','user','apex','bone','data']
# angband/adapter/an_main.cpp resolves both of these relative to portable::exe_dir(),
# which on Linux/Android is the process cwd (design section 2;
# platform/portable/legacy_os.cpp exe_dir()). The UI sets cwd to the per-user data directory
# before starting any core (platform/linux/user_data.cpp), so -- like the other cores'
# mapping.csv/terrain_map.csv entries below -- these must be shared (copied+linked) files,
# not left for the AngbandCore process to find beside its own binary.
MAPPINGS=['gensoband/tilework/mapping.csv','silq/tilework/terrain_map.csv','frox/tilework/terrain_map.csv','frox/tilework/mapping.csv',
 'tilework/tile_mapping.csv','angband/tilework/mapping.csv','toband/tilework/mapping.csv']
CORE_NAMES=['HengbandCore','TangbandCore','GensobandCore','TobandCore','SilCore','FroxCore','Rogue2Core','Rogue36Core','Rogue54Core','AngbandCore','UmoriaCore']
LINKS=['assets','gensoband/assets','toband/assets','silq/assets','frox/assets','angband/assets',*MAPPINGS]
SYSTEM_RE=re.compile(r'^(?:ld-linux|libc\.|libm\.|libdl\.|libpthread\.|librt\.|libresolv\.|libnss_|libGL\.|libGLX|libGLdispatch|libEGL|libGLES|libvulkan|libdrm|libgbm)')
def digest(p):
 with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
def excluded(rel):
 if any(x.startswith('.hd2d-save-') or x in ('.git','__pycache__') for x in rel.parts):return True
 if rel.name.endswith(('.bak','.orig')) or rel.name=='desktop.ini' or rel.as_posix()=='frox/lib-ja/edit/help_upd.txt':return True
 if '/xtra/graf/' in '/'+rel.as_posix()+'/':return True
 for root in LIB_ROOTS:
  if any(rel.as_posix().startswith(root+'/'+m+'/') for m in MUTABLE):return True
 return False
def dcss_sources(root):
 """The prepared DCSS original tree (tools/core_sources/prepare.py): HENGBAND_CORE_SOURCE_ROOT or ../roguelike-cores/build-sources."""
 base=Path(os.environ['HENGBAND_CORE_SOURCE_ROOT']) if os.environ.get('HENGBAND_CORE_SOURCE_ROOT') else root.parent/'roguelike-cores/build-sources'
 return base/'dcss'
def assets(root,stage,with_dcss=False,dcss_lib=None):
 files={}
 # (folder in the package, where to read it from). The DCSS data come from dcss_lib (default <root>/dcss/lib), which must match the
 # DcssCore being packed: dat/dlua/tags.lua and docs/FAQ.html etc. are generated, so on Linux make it from the build's mirror:
 #   python3 tools/dcss/prepare_runtime_data.py --work <build>/dcss-work --dest <dir>   and pass --dcss-lib <dir>.
 data_dirs=[(f,root/f) for f in DATA_DIRS]
 if with_dcss:
  lib=Path(dcss_lib) if dcss_lib else root/'dcss/lib'
  for folder in DCSS_DATA_DIRS:
   src=lib/folder[len('dcss/lib/'):]
   if not src.is_dir():raise FileNotFoundError(str(src)+' is missing: run tools/dcss/prepare_runtime_data.py (needs dcss/assets/atlas for tiles; see --dcss-lib)')
   data_dirs.append((folder,src))
 # Original game data is not in the repository: copy it first (python tools/core_sources/prepare_original_data.py).
 for need in ('angband/lib/gamedata','rogue2/mesg'):
  if not (root/need).exists():raise FileNotFoundError(str(root/need)+' is missing: run tools/core_sources/prepare_original_data.py')
 # angband/lib-ja is a generated, untracked tree ; rebuild it from angband/lang/ja/desc.
 subprocess.run(['python3' if os.name!='nt' else 'python',str(root/'tools/angband/an_build_ja_gamedata.py'),'build'],cwd=root,check=True)
 # the in-game help translation (angband/lib-ja/help,  section 18)
 subprocess.run(['python3' if os.name!='nt' else 'python',str(root/'tools/angband/an_build_ja_help.py'),'build'],cwd=root,check=True)
 # umoria/data is untracked upstream text; write it from the pinned upstream commit.
 subprocess.run(['python3' if os.name!='nt' else 'python',str(root/'tools/umoria/build_windows.py'),'--data-only'],cwd=root,check=True)
 for folder,source in data_dirs:
  if not source.is_dir():
   if folder in OPTIONAL_DATA_DIRS:continue
   raise FileNotFoundError(source)
  for p in sorted(source.rglob('*')):
   if not p.is_file():continue
   rel=Path(folder)/p.relative_to(source)
   if excluded(rel):continue
   dst=stage/rel;dst.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,dst);files[rel.as_posix()]=digest(dst)
 for name in MAPPINGS:
  dst=stage/name;dst.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(root/name,dst);files[name]=digest(dst)
 # RogueClone2's Japanese message catalogue is runtime data, not embedded in the core.
 r2_mesg=root/'rogue2/mesg'
 if not r2_mesg.is_file():raise FileNotFoundError(r2_mesg)
 r2_dst=stage/'rogue2/mesg';r2_dst.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(r2_mesg,r2_dst);files['rogue2/mesg']=digest(r2_dst)
 links=list(LINKS)+(DCSS_DATA_DIRS if with_dcss else [])
 for name in ['LICENSE','README.md','readme-hengband.md','THIRD-PARTY-NOTICES.txt','readme_angband']:
  if (root/name).exists():shutil.copy2(root/name,stage/name)
 # Keep the exact upstream license texts beside the package documentation.
 rogue_upstream=Path(os.environ['HENGBAND_UPSTREAM_ROOT']) if os.environ.get('HENGBAND_UPSTREAM_ROOT') else root.parent/'roguelike-cores/upstream'
 license_dir=stage/'licenses';license_dir.mkdir(parents=True,exist_ok=True)
 for core,out_name in [('rogue36','Rogue36-LICENSE.txt'),('rogue54','Rogue54-LICENSE.txt')]:
  src=rogue_upstream/core/'LICENSE.TXT'
  if not src.is_file():raise FileNotFoundError(src)
  dst=license_dir/out_name;shutil.copy2(src,dst);files[dst.relative_to(stage).as_posix()]=digest(dst)
 # TOband: Moria/Angband licence texts, the Japanese licence (jlicense.txt, EUC-JP upstream; written here as UTF-8),
 # and the NetHack General Public License (the Brynhild quest maps derive from NetHack). Design doc section 9.
 toband_upstream=rogue_upstream/'toband'
 for out_name,rel,source_encoding in [('Toband-readme_angband.txt','readme_angband',None),('Toband-nethack-license.txt','lib/file/nethack-license.txt',None),('Toband-jlicense.txt','lib/help/jlicense.txt','euc-jp')]:
  src=toband_upstream/rel
  if not src.is_file():raise FileNotFoundError(src)
  dst=license_dir/out_name
  if source_encoding:dst.write_bytes(src.read_bytes().decode(source_encoding).encode('utf-8'))
  else:shutil.copy2(src,dst)
  files[dst.relative_to(stage).as_posix()]=digest(dst)
 # Umoria's GPL v3 (the upstream LICENSE, written into umoria/data by build_windows.py --data-only).
 dst=license_dir/'Umoria-LICENSE.txt';shutil.copy2(root/'umoria/data/LICENSE',dst);files[dst.relative_to(stage).as_posix()]=digest(dst)
 # Angband's licence (GPL v2 is the chosen licence), the full text of the GPL v2, OpenAL Soft's LGPL v2 text, and the
 # RogueClone2 upstream documents (its condition (2): attach all the documents). Shared with the Windows/Android packages.
 dst=license_dir/'Angband-LICENSE.md';shutil.copy2(root/'angband/LICENSE.md',dst);files[dst.relative_to(stage).as_posix()]=digest(dst)
 sys.path.insert(0,str(Path(__file__).resolve().parent));import license_docs
 if with_dcss:
  # DCSS is GPL v2 or later (LICENSE); the bundled lua/sqlite/pcre/zlib notices, CREDITS.txt and the tile provenance lists go with it.
  for name in license_docs.copy_dcss(license_dir,dcss_sources(root)):files['licenses/'+name]=digest(license_dir/name)
 for name in [*license_docs.copy_gpl(license_dir),*license_docs.copy_openal(license_dir),*license_docs.copy_rogue2_docs(license_dir,rogue_upstream)]:
  files['licenses/'+name]=digest(license_dir/name)
 # Reuse the checked-in/generated Japanese font and retain its license.
 font=next((p for p in [root/'android/build-assets-hd2d/assets/fonts/placeholder_mono.ttf',root/'build-linux/fontcache/NotoSansMonoCJKjp-Regular.otf'] if p.is_file()),None)
 if not font:raise FileNotFoundError('Build the Japanese font assets first')
 (stage/'assets/fonts').mkdir(parents=True,exist_ok=True);shutil.copy2(font,stage/'assets/fonts/placeholder_mono.ttf')
 files['assets/fonts/placeholder_mono.ttf']=digest(stage/'assets/fonts/placeholder_mono.ttf')
 font_license=next((p for p in [root/'android/build-assets-hd2d/assets/fonts/LICENSE-NotoSansMonoCJK.txt',root/'build-linux/fontcache/LICENSE-NotoSansMonoCJK.txt'] if p.is_file()),None)
 if not font_license:raise FileNotFoundError('Japanese font license')
 shutil.copy2(font_license,stage/'assets/fonts/LICENSE-NotoSansMonoCJK.txt')
 files['assets/fonts/LICENSE-NotoSansMonoCJK.txt']=digest(stage/'assets/fonts/LICENSE-NotoSansMonoCJK.txt')
 forbidden=[name for name in files if Path(name).suffix.lower() in ('.png','.bmp','.jpg','.jpeg','.webp')
  and ('/tilework/' in '/'+name or name.startswith('assets/tiles/') or '/lib/xtra/graf/' in '/'+name+'/')]
 if forbidden:raise RuntimeError('Tile image entered Linux package: '+forbidden[0])
 mutable=[root+'/'+m for root in LIB_ROOTS for m in MUTABLE]
 for folder in mutable:
  (stage/folder).mkdir(parents=True,exist_ok=True)
  (stage/folder/'delete.me').touch()
 copies={name:hash for name,hash in files.items() if not any(name==p or name.startswith(p+'/') for p in links)}
 directories=[*mutable,*(DCSS_USER_DIRS if with_dcss else [])]
 manifest={'schema':1,'copies':copies,'links':links,'directories':directories}
 (stage/'linux-data.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
 print('ASSETS',len(files),'copied user-data files',len(copies),flush=True)
 return files
def libraries(stage,binaries):
 runtime=stage/'runtime';runtime.mkdir()
 pending=list(binaries);seen={};sources={};owners=set()
 while pending:
  binary=pending.pop();result=subprocess.check_output(['ldd',str(binary)],text=True)
  if 'not found' in result:raise RuntimeError(result)
  for line in result.splitlines():
   match=re.match(r'\s*(\S+) => (/\S+) \(',line)
   if not match:continue
   name,source=match.groups()
   if SYSTEM_RE.match(name) or name in seen:continue
   src=Path(source).resolve();dest=runtime/name
   shutil.copy2(src,dest);seen[name]=digest(dest);sources[name]=str(src);pending.append(src)
   owner=subprocess.run(['dpkg-query','-S',str(src)],capture_output=True,text=True)
   if owner.returncode==0:
    for x in owner.stdout.splitlines():owners.add(x.split(': /',1)[0])
 for p in [*binaries,*runtime.iterdir()]:
  subprocess.run(['patchelf','--set-rpath','$ORIGIN' if p.parent==runtime else '$ORIGIN/runtime:$ORIGIN/../runtime',str(p)],check=True)
 license_dir=stage/'licenses/linux-runtime';license_dir.mkdir(parents=True)
 for owner in sorted(owners):
  pkg=owner.split(':')[0];source=Path('/usr/share/doc')/pkg/'copyright'
  if source.is_file():shutil.copy2(source,license_dir/(pkg+'.txt'))
  else:raise FileNotFoundError('Runtime license missing: '+pkg)
 return {'libraries':{p.name:digest(p) for p in runtime.iterdir()},'source_libraries':sources,'license_packages':sorted(owners)}
def main():
 p=argparse.ArgumentParser();p.add_argument('--root',type=Path,required=True);p.add_argument('--bin',type=Path);p.add_argument('--out',type=Path,required=True);p.add_argument('--version',default=time.strftime('%Y-%m-%d'));p.add_argument('--assets-only',action='store_true')
 p.add_argument('--dcss-lib',type=Path,help='where the DCSS data (dat, docs, settings, tiles) are read from; default <root>/dcss/lib. On Linux make it with tools/dcss/prepare_runtime_data.py --work <build>/dcss-work --dest <dir>')
