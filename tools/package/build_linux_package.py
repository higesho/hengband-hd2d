 if final_stage.exists():raise FileExistsError('Choose a fresh output directory: '+str(final_stage))
 on_9p=out.as_posix().startswith('/mnt/') and 'microsoft' in Path('/proc/version').read_text().lower()
 stage_root=a.stage_root.resolve() if a.stage_root else (Path(tempfile.mkdtemp(prefix='hb-stage-',dir=Path.home())) if on_9p else None)
 if a.assets_only or stage_root is None:stage_root=out
 stage=stage_root/name
